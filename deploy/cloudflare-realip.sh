#!/usr/bin/env bash
# Makes nginx see the visitor's real address instead of Cloudflare's. On the VPS, as root:
#   sudo bash /var/www/Fitness/deploy/cloudflare-realip.sh
# Idempotent; re-run it now and then to pick up new Cloudflare ranges. Called by
# setup-server.sh.
#
# trainwithparia.com is proxied by Cloudflare, so the TCP peer nginx sees ($remote_addr)
# is a Cloudflare edge, and a different one from request to request. The visit counter
# hashes IP + User-Agent (src/lib/analytics.ts), so one device opening the site counted
# as a new unique visitor almost every time, while unrelated people sharing an edge were
# merged into one.
#
# realip replaces $remote_addr with CF-Connecting-IP, but only for connections that come
# from Cloudflare's published ranges. Trusting the header from anyone would let a
# client that connects to the server's IP directly put any address in it.
set -euo pipefail

CONF=/etc/nginx/conf.d/cloudflare-realip.conf
TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT

{
  echo "# Generated by deploy/cloudflare-realip.sh - do not edit by hand."
  for list in ips-v4 ips-v6; do
    curl -fsS --max-time 20 "https://www.cloudflare.com/$list" |
      grep -E '^[0-9a-fA-F:.]+/[0-9]+$' |
      sed 's/^/set_real_ip_from /; s/$/;/'
  done
  echo "real_ip_header CF-Connecting-IP;"
} > "$TMP"

# An empty or truncated download must not replace a working config.
count=$(grep -c '^set_real_ip_from' "$TMP")
if [ "$count" -lt 10 ]; then
  echo "only $count Cloudflare ranges downloaded; leaving $CONF unchanged" >&2
  exit 1
fi

if [ -f "$CONF" ] && cmp -s "$TMP" "$CONF"; then
  echo "cloudflare realip: up to date ($count ranges)"
  exit 0
fi

[ -f "$CONF" ] && cp -a "$CONF" "$CONF.bak"
install -m 644 "$TMP" "$CONF"
if nginx -t; then
  systemctl reload nginx
  echo "cloudflare realip: installed $count ranges"
else
  if [ -f "$CONF.bak" ]; then mv "$CONF.bak" "$CONF"; else rm -f "$CONF"; fi
  echo "nginx rejected the config; restored the previous state" >&2
  exit 1
fi
